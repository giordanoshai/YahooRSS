"""
services/prompts.py - Prompt 模板库

提供每日盘前、盘后宏观研报生成的系统提示词。
以资深买方策略师口吻构建结构化专业报告。
"""


def get_daily_summary_prompts(prompt_type: str, content: str) -> str:
    """根据盘前/盘后生成买方策略报告 Prompt"""
    base_role = """你是资深买方策略师。
严格基于所提供的新闻内容生成报告，禁止添加任何新闻中未提及的信息。
对于条目众多的新闻，自动忽略低影响力内容，聚焦最关键的 10 条以内。"""

    if prompt_type == "postmarket":
        return f"""{base_role}

新闻数据（盘中/盘后）：{content}

按以下格式输出，总字数控制在 500 字以内：

【盘中回顾】
标普500/纳指：涨跌幅 + 一句话定性
异动个股/板块：标的 → 方向 → 原因（每条15字内，列2-3条）

【核心驱动】
列出3条最关键的市场驱动主题，每条格式：
主题名 → 核心内容 → 影响方向（利多↑ / 利空↓ / 中性→）

【数据/财报】
逐条列出，格式：名称 → 结果 → 影响（若无则写"无"）

【明日关注标的】
列3-5个，格式：标的 → 多/空 → 一句话理由

【主要风险】
1-2条，每条20字以内"""

    elif prompt_type == "premarket":
        return f"""{base_role}

新闻数据（过去24小时/盘前）：{content}

按以下格式输出，总字数控制在 500 字以内：

【核心驱动】
列出3条最关键的市场驱动主题，每条格式：
主题名 → 核心内容 → 影响方向（利多↑ / 利空↓ / 中性→）

【数据/财报】
逐条列出，格式：名称 → 结果 → 影响（若无则写"无"）

【今日关注标的】
列3-5个，格式：标的 → 多/空 → 一句话理由

【主要风险】
1-2条，每条20字以内"""

    else:
        raise ValueError(f"无效的 prompt 类型: {prompt_type}")
